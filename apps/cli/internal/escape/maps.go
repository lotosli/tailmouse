// Package escape owns the host-authoritative game without transport or UI dependencies.
package escape

import (
	"errors"
	"math/rand/v2"
	"slices"
	"strings"
)

const (
	MapWidth  = 48
	MapHeight = 18
)

var ErrInvalidMap = errors.New("invalid escape map")

// Point is a position in logical cells; initial entities occupy cell centers.
type Point struct{ X, Y float32 }

// Map is a value snapshot. Rows contain only walls (#) and floor (.).
type Map struct {
	Name   string
	Rows   [MapHeight]string
	Mouse  Point
	Cat    Point
	Cheese [2]Point
	Exit   Point
}

func MapNames() [5]string {
	return [5]string{"courtyard", "pantry", "corridors", "switchbacks", "crossroads"}
}

// SelectMap selects only checked-in layouts. Named maps ignore the seed; random
// selection uses a private deterministic generator, never process-wide state.
func SelectMap(name string, seed int64) (Map, error) {
	names := MapNames()
	index := slices.Index(names[:], name)
	if name == "random" {
		index = rand.New(rand.NewPCG(uint64(seed), 0x544d4f555345)).IntN(len(names))
	}
	if index < 0 {
		return Map{}, ErrInvalidMap
	}
	layouts := [5]string{courtyard, pantry, corridors, switchbacks, crossroads}
	return parseMap(names[index], layouts[index])
}

func (layout Map) Walkable(x, y int) bool {
	return x >= 0 && x < MapWidth && y >= 0 && y < MapHeight &&
		len(layout.Rows[y]) == MapWidth && layout.Rows[y][x] == '.'
}

// parseMap is for the fixed, local map assets, not remotely supplied level data.
func parseMap(name, text string) (Map, error) {
	if len(text) != MapHeight*MapWidth+MapHeight-1 {
		return Map{}, ErrInvalidMap
	}
	rows := strings.Split(text, "\n")
	if len(rows) != MapHeight {
		return Map{}, ErrInvalidMap
	}
	result := Map{Name: name}
	var seen uint8
	var positions [5]Point
	for y, textRow := range rows {
		if len(textRow) != MapWidth {
			return Map{}, ErrInvalidMap
		}
		row := []byte(textRow)
		for x, cell := range row {
			if (x == 0 || x == MapWidth-1 || y == 0 || y == MapHeight-1) && cell != '#' {
				return Map{}, ErrInvalidMap
			}
			switch cell {
			case '#', '.':
			case 'M', 'C', '1', '2', 'E':
				index := strings.IndexByte("MC12E", cell)
				bit := uint8(1 << index)
				if seen&bit != 0 {
					return Map{}, ErrInvalidMap
				}
				seen |= bit
				positions[index] = Point{X: float32(x) + 0.5, Y: float32(y) + 0.5}
				row[x] = '.'
			default:
				return Map{}, ErrInvalidMap
			}
		}
		result.Rows[y] = string(row)
	}
	if seen != 31 {
		return Map{}, ErrInvalidMap
	}
	result.Mouse, result.Cat, result.Cheese, result.Exit = positions[0], positions[1], [2]Point{positions[2], positions[3]}, positions[4]
	return result, nil
}

